#!/bin/sh
# Prints woma's Homebrew formula for a release tag: brew builds woma from the
# tag's source archive (Go, at install time), so the binary is never
# quarantined and needs no signing. docs/releasing.md has where it goes.
#
#   scripts/formula.sh v0.1.0 > ../homebrew-tap/Formula/woma.rb
#   WOMA_ARCHIVE=path/to.tar.gz scripts/formula.sh v0.1.0   # its sha256 from a local archive
set -eu

tag="${1:?usage: scripts/formula.sh <tag, e.g. v0.1.0>}"
url="https://github.com/carlosrberto/woma/archive/refs/tags/$tag.tar.gz"

if [ -n "${WOMA_ARCHIVE:-}" ]; then
	sha=$(shasum -a 256 "$WOMA_ARCHIVE" | cut -d' ' -f1)
else
	sha=$(curl -fsSL "$url" | shasum -a 256 | cut -d' ' -f1)
fi

cat <<EOF
# Generated by scripts/formula.sh in carlosrberto/woma - don't edit by hand.
class Woma < Formula
  desc "Find, inspect and clean up git worktrees"
  homepage "https://github.com/carlosrberto/woma"
  url "$url"
  sha256 "$sha"
  license "MIT"
  head "https://github.com/carlosrberto/woma.git", branch: "main"

  depends_on "go" => :build

  def install
    system "go", "build", *std_go_args(ldflags: "-s -w -X main.version=#{version}")
  end

  def caveats
    <<~TEXT
      For wcd and wnew (cd into a picked or new worktree), add to ~/.zshrc or ~/.bashrc:
        eval "\$(woma shell-init)"
    TEXT
  end

  test do
    assert_match "woma #{version}", shell_output("#{bin}/woma version")
  end
end
EOF
