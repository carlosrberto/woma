#!/bin/sh
# Prints woma's Homebrew formula for a release tag: brew downloads the
# release's prebuilt binary for the machine (macOS or Linux, arm64 or
# amd64). Homebrew doesn't quarantine what it downloads, so macOS runs the
# binary without it being signed or notarized. --HEAD builds main from
# source instead. docs/releasing.md has where the formula goes.
#
#   scripts/formula.sh v0.2.0 > ../homebrew-tap/Formula/woma.rb
#   scripts/formula.sh v0.2.0 dist/checksums.txt   # checksums from a local `make dist`
set -eu

tag="${1:?usage: scripts/formula.sh <tag, e.g. v0.2.0> [checksums.txt]}"
version="${tag#v}"
base="https://github.com/carlosrberto/woma/releases/download/$tag"

if [ -n "${2:-}" ]; then
	sums=$(cat "$2")
else
	sums=$(curl -fsSL "$base/checksums.txt")
fi

sha() {
	s=$(printf '%s\n' "$sums" | awk -v f="woma_${version}_$1.tar.gz" '$2 == f {print $1}')
	[ -n "$s" ] || {
		echo "formula: no checksum for woma_${version}_$1.tar.gz" >&2
		exit 1
	}
	echo "$s"
}

darwin_arm64=$(sha darwin_arm64)
darwin_amd64=$(sha darwin_amd64)
linux_arm64=$(sha linux_arm64)
linux_amd64=$(sha linux_amd64)

cat <<EOF
# Generated by scripts/formula.sh in carlosrberto/woma - don't edit by hand.
class Woma < Formula
  desc "Find, inspect and clean up git worktrees"
  homepage "https://github.com/carlosrberto/woma"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/woma_${version}_darwin_arm64.tar.gz"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/woma_${version}_darwin_amd64.tar.gz"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$base/woma_${version}_linux_arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/woma_${version}_linux_amd64.tar.gz"
      sha256 "$linux_amd64"
    end
  end

  head do
    url "https://github.com/carlosrberto/woma.git", branch: "main"
    depends_on "go" => :build
  end

  def install
    if build.head?
      system "go", "build", *std_go_args(ldflags: "-s -w -X main.version=#{version}")
    else
      bin.install "woma"
    end
  end

  def caveats
    <<~TEXT
      For wcd and wnew (cd into a picked or new worktree), add to ~/.zshrc or ~/.bashrc:
        eval "\$(woma shell-init)"
    TEXT
  end

  test do
    assert_match "woma #{version}", shell_output("#{bin}/woma version")
  end
end
EOF
